def style_cell(cell, font=BODY_FONT, align=RTL_ALIGN, fill=None):
    cell.font = font
    cell.alignment = align
    if fill:
        cell.fill = fill


def write_header_block(ws: Worksheet, title: str, role: str, row_count: str, grain: str) -> int:
    ws.sheet_view.rightToLeft = True
    r = 1
    ws.cell(row=r, column=1, value=title)
    style_cell(ws.cell(row=r, column=1), TITLE_FONT, RTL_ALIGN)
    ws.merge_cells(start_row=r, start_column=1, end_row=r, end_column=8)
    r += 1
    for label, value in [
        ("نقش جدول در پروژه", role),
        ("تعداد کل رکورد (اندازه‌گیری واقعی، ۲۰۲۶-۰۸-۳۰)", row_count),
        ("گرین (Grain) — هر رکورد نماینده‌ی چیست؟", grain),
    ]:
        ws.cell(row=r, column=1, value=label)
        style_cell(ws.cell(row=r, column=1), SUBTITLE_FONT, RTL_ALIGN, SECTION_FILL)
        ws.cell(row=r, column=2, value=value)
        style_cell(ws.cell(row=r, column=2), BODY_FONT, RTL_ALIGN)
        ws.merge_cells(start_row=r, start_column=2, end_row=r, end_column=8)
        r += 1
    r += 1
    return r


def write_columns_table(ws: Worksheet, start_row: int, rows: list) -> int:
    r = start_row
    for i, h in enumerate(COL_HEADERS, start=1):
        c = ws.cell(row=r, column=i, value=h)
        style_cell(c, HEADER_FONT, Alignment(horizontal="center", vertical="center", wrap_text=True, readingOrder=2), HEADER_FILL)
    header_row = r
    r += 1
    for row_data in rows:
        for i, val in enumerate(row_data, start=1):
            c = ws.cell(row=r, column=i, value=val)
            align = RTL_ALIGN_LEFT_NUM if i in (6, 7) and isinstance(val, (int, float)) else RTL_ALIGN
            style_cell(c, BODY_FONT, align)
        r += 1
    for i, w in enumerate(COL_WIDTHS, start=1):
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = ws.cell(row=header_row + 1, column=1).coordinate
    return r + 1


def write_duplicate_section(ws: Worksheet, start_row: int, dup_count, remove_decision: str, filter_reco: str) -> int:
    r = start_row
    ws.cell(row=r, column=1, value="تحلیل تکرار و کیفیت رکورد")
    style_cell(ws.cell(row=r, column=1), SUBTITLE_FONT, RTL_ALIGN, SECTION_FILL)
    ws.merge_cells(start_row=r, start_column=1, end_row=r, end_column=8)
    r += 1
    for label, value in [
        ("تعداد رکورد تکراری روی کلید طبیعی جدول", dup_count),
        ("آیا این تکرار باید حذف شود؟", remove_decision),
        ("توصیه‌ی فیلتر/حذف قبل از تحلیل", filter_reco),
    ]:
        ws.cell(row=r, column=1, value=label)
        style_cell(ws.cell(row=r, column=1), BODY_FONT, RTL_ALIGN)
        ws.cell(row=r, column=2, value=value)
        style_cell(ws.cell(row=r, column=2), BODY_FONT, RTL_ALIGN)
        ws.merge_cells(start_row=r, start_column=2, end_row=r, end_column=8)
        r += 1
    return r


def build_sheet(wb, sheet_name, title, role, row_count, grain, columns_rows, dup_count, remove_decision, filter_reco):
    ws = wb.create_sheet(sheet_name[:31])
    r = write_header_block(ws, title, role, row_count, grain)
    r = write_columns_table(ws, r, columns_rows)
    write_duplicate_section(ws, r, dup_count, remove_decision, filter_reco)
    return ws



SET NOCOUNT ON;
USE Alzahra_Final_DB;
SELECT LEFT(OPEN_DATE,4) AS open_year, COUNT(*) AS cnt
FROM Deposit_Accoutnt_Info
GROUP BY LEFT(OPEN_DATE,4)
HAVING LEFT(OPEN_DATE,4) IN ('1300','1301','1390','1900') OR CAST(LEFT(OPEN_DATE,4) AS INT) < 1375
ORDER BY cnt DESC;
SELECT COUNT(DISTINCT LTRIM(RTRIM(MAIN_CUSTOMER_ID))) AS affected_customers
FROM Deposit_Accoutnt_Info WHERE OPEN_DATE = '1300/01/01';
